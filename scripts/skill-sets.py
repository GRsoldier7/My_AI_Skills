#!/usr/bin/env python3
"""Validate curated packages and generate installer-compatible profiles. Stdlib only."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path, PurePosixPath
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
BASE = 'platform-configs/skill-sets'
START = '<!-- CURATED-SETS:START -->'
END = '<!-- CURATED-SETS:END -->'
SLUG = re.compile(r'[a-z0-9]+(?:-[a-z0-9]+)*\Z')
STATUSES = {'trial', 'active', 'reference', 'deprecated'}
SET_HEADER = '# Generated by python3 scripts/skill-sets.py --write; edit manifest.json.\n'


def safe_path(root: Path, relative: str) -> Path:
    """Reject traversal and symlinks rather than following external content."""
    parts = PurePosixPath(relative).parts
    if not parts or relative.startswith('/') or '\\' in relative or any(p in ('.', '..') for p in relative.split('/')):
        raise ValueError(f'Unsafe path: {relative}')
    path = root
    for part in parts:
        path = path / part
        if path.is_symlink():
            raise ValueError(f'Symlink refused: {relative}')
    if not path.resolve().is_relative_to(root.resolve()):
        raise ValueError(f'Path outside repository: {relative}')
    return path


def package_hash(folder: Path) -> str:
    """Hash all package filenames and exact bytes, including references and licenses."""
    if folder.is_symlink():
        raise ValueError(f'Symlink package: {folder}')
    digest = hashlib.sha256()
    for path in sorted(folder.rglob('*')):
        if path.is_symlink():
            raise ValueError(f'Symlink resource: {path}')
        if path.is_file():
            digest.update(path.relative_to(folder).as_posix().encode('utf-8') + b'\0')
            content = path.read_bytes()
            digest.update(str(len(content)).encode('ascii') + b'\0' + content)
    return digest.hexdigest()


def markdown_links(text: str) -> list[str]:
    """Find live inline links, excluding fenced/inline code examples."""
    visible: list[str] = []
    fence = ''
    for line in text.splitlines():
        match = re.match(r'^\s*(`{3,}|~{3,})', line)
        if match:
            token = match[1]
            if not fence:
                fence = token
            elif token[0] == fence[0] and len(token) >= len(fence):
                fence = ''
            continue
        if not fence:
            visible.append(re.sub(r'(`+).*?\1', '', line))
    return re.findall(r'\]\(([^\s)]+)(?:\s+"[^"]*")?\)', '\n'.join(visible))


def resolve_profile(manifest: dict, name: str) -> list[dict]:
    """Resolve included profiles and required dependencies once in dependency order."""
    entries = {entry['id']: entry for entry in manifest['skills']}
    profiles = manifest['profiles']
    if name not in profiles:
        raise ValueError(f'Unknown profile: {name}')
    selected: list[str] = []

    def include(profile: str, visiting: set[str]) -> None:
        if profile in visiting or profile not in profiles:
            raise ValueError(f'Unknown or cyclic profile: {profile}')
        spec = profiles[profile]
        for parent in spec.get('includes', []):
            include(parent, visiting | {profile})
        selected.extend(spec.get('skills', []))

    include(name, set())
    result: list[dict] = []
    done: set[str] = set()

    def add(skill_id: str, visiting: set[str]) -> None:
        if skill_id in visiting or skill_id not in entries:
            raise ValueError(f'Unknown or cyclic dependency: {skill_id}')
        if skill_id in done:
            return
        entry = entries[skill_id]
        if entry['status'] not in ('active', 'trial'):
            raise ValueError(f'Profile selects non-installable {skill_id}: {entry["status"]}')
        if entry['status'] == 'trial' and profiles[name].get('allow_trial') is not True:
            raise ValueError(f'Profile has not opted into trial: {skill_id}')
        for dep in entry.get('dependencies', []):
            add(dep, visiting | {skill_id})
        done.add(skill_id)
        result.append(entry)

    for skill_id in selected:
        add(skill_id, set())
    return result


def validate(root: Path, manifest: dict, check_hashes: bool = True) -> None:
    """Validate identities, complete packages, local links, status and selection."""
    if manifest.get('schema_version') != 1 or not isinstance(manifest.get('skills'), list):
        raise ValueError('Expected schema_version 1 and a skills array')
    if not isinstance(manifest.get('profiles'), dict):
        raise ValueError('Expected profiles object')
    identities: dict[str, str] = {}
    paths: set[str] = set()
    ids: set[str] = set()
    for entry in manifest['skills']:
        for key in ('id', 'name', 'path', 'status', 'provenance', 'package_sha256'):
            if key not in entry:
                raise ValueError(f'Missing manifest field: {key}')
        skill_id = entry['id']
        if skill_id in ids:
            raise ValueError(f'Duplicate stable ID: {skill_id}')
        ids.add(skill_id)
        if not SLUG.fullmatch(skill_id) or entry['status'] not in STATUSES:
            raise ValueError(f'Invalid ID/status: {skill_id}')
        if entry['path'] in paths or not entry['path'].startswith('skills/'):
            raise ValueError(f'Duplicate/noncanonical path: {entry["path"]}')
        paths.add(entry['path'])
        folder = safe_path(root, entry['path'])
        main = folder / 'SKILL.md'
        if not main.is_file():
            raise ValueError(f'Missing SKILL.md: {entry["path"]}')
        text = main.read_text(encoding='utf-8')
        frontmatter = re.match(r'^---\n(.*?)\n---(?:\n|$)', text, re.S)
        match = re.search(r'^name:\s*[\"\']?([a-z0-9_-]+)[\"\']?\s*$', frontmatter[1], re.M) if frontmatter else None
        if not match or match[1] != entry['name']:
            raise ValueError(f'Declared name mismatch: {entry["path"]}')
        if not entry['provenance'].get('kind'):
            raise ValueError(f'Missing provenance kind: {skill_id}')
        for token in [skill_id, entry['name'], folder.name, *entry.get('aliases', [])]:
            if token in identities and identities[token] != skill_id:
                raise ValueError(f'Identity collision: {token}')
            identities[token] = skill_id
        actual = package_hash(folder)
        if check_hashes and actual != entry['package_sha256']:
            raise ValueError(f'Package changed; review before --refresh-hashes: {skill_id}')
        for resource in folder.rglob('*.md'):
            for target in markdown_links(resource.read_text(encoding='utf-8')):
                if re.match(r'^[a-zA-Z][a-zA-Z0-9+.-]*:', target) or target.startswith('#'):
                    continue
                target = target.split('#', 1)[0]
                destination = (resource.parent / target).resolve()
                if not destination.is_relative_to(folder.resolve()) or not destination.is_file():
                    raise ValueError(f'Missing/outside-package reference in {resource}: {target}')
    for name in manifest['profiles']:
        if not SLUG.fullmatch(name):
            raise ValueError(f'Invalid profile name: {name}')
        if name == 'global':
            raise ValueError('global is reserved for the existing unmanaged default set')
        resolve_profile(manifest, name)


def generate(root: Path, write: bool = False, refresh_hashes: bool = False) -> dict[str, str]:
    """Check drift by default; writes require an explicit flag and full preflight."""
    manifest_path = safe_path(root, BASE + '/manifest.json')
    manifest = json.loads(manifest_path.read_text(encoding='utf-8'))
    validate(root, manifest, check_hashes=not refresh_hashes)
    if refresh_hashes:
        for entry in manifest['skills']:
            entry['package_sha256'] = package_hash(safe_path(root, entry['path']))
    outputs: dict[str, str] = {}
    catalog = ['## Curated pilot profiles', '',
               'Generated from `manifest.json`. All trial profiles require deliberate selection; `global.txt` is unchanged.', '',
               '| Profile | Packages | Trial | Selection |', '|---|---:|---:|---|']
    for name in sorted(manifest['profiles']):
        entries = resolve_profile(manifest, name)
        outputs[name + '.txt'] = SET_HEADER + '\n'.join(e['path'] for e in entries) + '\n'
        catalog.append(f'| [{name}]({name}.txt) | {len(entries)} | {sum(e["status"] == "trial" for e in entries)} | ' + ', '.join(e['name'] for e in entries) + ' |')
    catalog.extend(['', '| Skill | Canonical path | Status |', '|---|---|---|'])
    catalog.extend(f'| {e["name"]} | {e["path"]} | {e["status"]} |' for e in sorted(manifest['skills'], key=lambda e: e['id']))
    section = START + '\n' + '\n'.join(catalog) + '\n' + END
    readme = safe_path(root, BASE + '/README.md')
    original = readme.read_text(encoding='utf-8') if readme.exists() else ''
    if original.count(START) != original.count(END) or original.count(START) > 1:
        raise ValueError('Ambiguous generated README markers')
    if START in original:
        begin, end = original.index(START), original.index(END) + len(END)
        outputs['README.md'] = original[:begin] + section + original[end:]
    else:
        outputs['README.md'] = original.rstrip() + '\n\n' + section + '\n'
    if refresh_hashes:
        outputs['manifest.json'] = json.dumps(manifest, indent=2, ensure_ascii=False) + '\n'
    targets = {name: safe_path(root, BASE + '/' + name) for name in outputs}
    orphaned = [p.name for p in (root / BASE).glob('*.txt')
                if not p.is_symlink() and p.is_file() and p.name not in outputs
                and p.read_text(encoding='utf-8').startswith(SET_HEADER)]
    if orphaned:
        raise ValueError('Orphaned generated sets; explicitly retire them after review: ' + ', '.join(sorted(orphaned)))
    for name, path in targets.items():
        if path.exists() and not path.is_file():
            raise ValueError(f'Output is not a regular file: {path}')
        if name.endswith('.txt') and path.exists() and not path.read_text(encoding='utf-8').startswith(SET_HEADER):
            raise ValueError(f'Refusing unmanaged set collision: {name}')
    if write:
        for name, path in targets.items():
            if not path.exists() or path.read_text(encoding='utf-8') != outputs[name]:
                path.write_text(outputs[name], encoding='utf-8', newline='\n')
    else:
        changed = [name for name, path in targets.items() if not path.is_file() or path.read_text(encoding='utf-8') != outputs[name]]
        if changed:
            raise ValueError('Generated files are stale: ' + ', '.join(changed))
    return outputs


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true', help='Regenerate curated set files/catalog')
    parser.add_argument('--refresh-hashes', action='store_true', help='Record reviewed package bytes; requires --write')
    args = parser.parse_args()
    if args.refresh_hashes and not args.write:
        parser.error('--refresh-hashes requires --write after reviewing changes')
    try:
        outputs = generate(ROOT, args.write, args.refresh_hashes)
    except (ValueError, KeyError, TypeError, OSError) as exc:
        print(f'ERROR: {exc}', file=sys.stderr)
        return 1
    print(f'Curated profiles {"written" if args.write else "verified"}: {len(outputs) - 1 - int(args.refresh_hashes)} sets; no installations performed.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
