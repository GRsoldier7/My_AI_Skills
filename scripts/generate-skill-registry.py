_STOP = set("""a an and the or of to for in on with by from as at is are be use when this that it its
into your you any not no only each per via than then also over under after before about while
skill skills user users asks wants need needs task tasks work using used run runs""".split())


def _load_json(path: Path) -> dict[str, Any]:
    import json

    return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else {}


def _fenced_roots(curation: dict[str, Any]) -> dict[str, Path]:
    return {
        agent: REPO_DIR / spec["path"]
        for agent, spec in (curation.get("fenced") or {}).items()
    }


def _detect_license(skill_dir: Path, fm: dict[str, Any], third_party: dict[str, Any], rel: str) -> str:
    if rel in third_party:
        return str(third_party[rel].get("license", ""))
    if fm.get("license"):
        return str(fm["license"]).strip()
    for f in sorted(skill_dir.iterdir(), key=lambda path: path.name):
        if f.is_file() and f.name.upper().startswith("LICENSE"):
            head = f.read_text(encoding="utf-8", errors="replace")[:400]
            if "MIT License" in head or "Permission is hereby granted" in head:
                return "MIT"
            if "Apache License" in head:
                return "Apache-2.0"
            return "see " + f.name
    return "none"


def _first_sentence(text: str, limit: int = 200) -> str:
    text = " ".join(str(text).split())
    guarded = re.sub(r"\b(e\.g|i\.e|etc|vs)\.", lambda m: m.group(1).replace(".", "\x00") + "\x00", text)
    m = re.match(r"(.+?[.!?])(\s|$)", guarded)
    out = (m.group(1) if m else guarded).replace("\x00", ".")
    out = re.sub(r"\s*[\u2014\u2013]\s*", ", ", out)  # table cells: no em or en dashes
    return out if len(out) <= limit else out[: limit - 3].rstrip() + "..."


_FULL_DESC: dict[str, str] = {}


def build_registry() -> tuple[list[dict[str, Any]], dict[str, Any]]:
    import fnmatch

    curation = _load_json(CURATION_FILE)
    third_party = curation.get("third_party") or {}
    vendored_globs = (_load_json(LINT_CONFIG).get("vendored_paths") or [])
    core_sets = {d: set(v) for d, v in (curation.get("core") or {}).items()}
    review = curation.get("review") or {}
    deprecated = curation.get("deprecated") or {}
    box_mirror = set(curation.get("box_mirror") or [])
    agent_lists = {a: set(spec.get("skills") or []) for a, spec in (curation.get("agents") or {}).items()}

    roots: list[tuple[Path, str | None]] = [(SKILLS_ROOT, None)]
    roots += [(root, agent) for agent, root in _fenced_roots(curation).items()]

    entries: list[dict[str, Any]] = []
    for root, fenced_for in roots:
        for path in find_skill_files(root):
            skill_dir = path.parent
            rel = skill_dir.relative_to(REPO_DIR).as_posix()
            fm = parse_frontmatter(path.read_text(encoding="utf-8"))
            meta = fm.get("metadata") if isinstance(fm.get("metadata"), dict) else {}
            dirname = skill_dir.name
            if fenced_for:
                domain = f"{fenced_for}-only"
            else:
                domain = _infer_category_from_path(path) or "uncategorized"
                if len(skill_dir.relative_to(SKILLS_ROOT).parts) == 1:
                    domain = dirname  # a skill that sits at category level
            if rel in deprecated:
                status = "deprecated"
            elif rel in review:
                status = "review"
            elif dirname in core_sets.get(domain, set()):
                status = "core"
            else:
                status = "optional"
            if rel in third_party or any(fnmatch.fnmatchcase(rel, g) for g in vendored_globs):
                origin = "vendored"
            elif dirname in box_mirror:
                origin = "box-mirror"
            else:
                origin = "library"
            platforms = sorted(a for a, names in agent_lists.items() if dirname in names)
            if fenced_for and fenced_for not in platforms:
                platforms = sorted(platforms + [fenced_for])
            entry = {
                "name": str(fm.get("name") or dirname),
                "dir": dirname,
                "path": rel,
                "domain": domain,
                "declared_domain": str((meta or {}).get("domain-category") or ""),
                "portable": fenced_for is None,
                "status": status,
                "platforms": platforms,
                "origin": origin,
                "license": _detect_license(skill_dir, fm, third_party, rel),
                "version": str((meta or {}).get("version") or fm.get("version") or ""),
                "manual_only": is_manual_only(path, fm),
                "summary": _first_sentence(fm.get("description") or ""),
            }
            _FULL_DESC[rel] = str(fm.get("description") or "")
            if rel in third_party:
                entry["upstream"] = third_party[rel].get("upstream", "")
                entry["upstream_commit"] = third_party[rel].get("commit", "")
            if rel in review:
                entry["review_reason"] = review[rel]
            entries.append(entry)
    entries.sort(key=lambda e: e["path"])
    return entries, curation


def render_registry_json(entries: list[dict[str, Any]], curation: dict[str, Any]) -> str:
    import json

    counts: dict[str, int] = defaultdict(int)
    for e in entries:
        counts[e["status"]] += 1
    doc = {
        "_comment": "Generated by scripts/generate-skill-registry.py --registry from every SKILL.md "
        "plus registry/curation.json. Do not hand-edit.",
        "schema": 1,
        "totals": {"skills": len(entries), "portable": sum(e["portable"] for e in entries), **dict(sorted(counts.items()))},
        "caps": curation.get("caps", {}),
        "skills": entries,
    }
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


def render_agent_block(agent: str, entries: list[dict[str, Any]], curation: dict[str, Any]) -> str:
    by_dir = {e["dir"]: e for e in entries}
    spec = (curation.get("agents") or {}).get(agent) or {}
    lines = [AGENT_START, "", "| Skill | Domain | Load it when | Path |", "|---|---|---|---|"]
    for name in spec.get("skills") or []:
        e = by_dir.get(name)
        if not e:
            lines.append(f"| `{name}` | missing | not found in this checkout | |")
            continue
        lines.append(
            f"| `{e['dir']}` | {e['domain']} | {_md_escape(e['summary'])} | [{e['path']}/SKILL.md](../{e['path']}/SKILL.md) |"
        )
    fenced = [e for e in entries if not e["portable"] and agent in e["platforms"] and e["dir"] not in (spec.get("skills") or [])]
    if fenced:
        lines += ["", f"Fenced {spec.get('title', agent)}-only skills (not portable):", "",
                  "| Skill | Load it when | Path |", "|---|---|---|"]
        for e in fenced:
            lines.append(f"| `{e['dir']}` | {_md_escape(e['summary'])} | [{e['path']}/SKILL.md](../{e['path']}/SKILL.md) |")
    lines += ["", AGENT_END]
    return "\n".join(lines)


def _apply_agent_block(text: str, block: str) -> str:
    if AGENT_START in text and AGENT_END in text:
        pre = text.split(AGENT_START, 1)[0]
        post = text.split(AGENT_END, 1)[1]
        return pre + block + post
    return text.rstrip("\n") + "\n\n" + block + "\n"


def _tokens(text: str) -> set[str]:
    return {w for w in re.findall(r"[a-z][a-z0-9-]{2,}", text.lower()) if w not in _STOP}


def _git_output(*args: str) -> bytes:
    env = {key: value for key, value in os.environ.items() if not key.startswith("GIT_")}
    env["GIT_NO_LAZY_FETCH"] = "1"
    return subprocess.run(
        ["git", "--git-dir=.git", "--work-tree=.", "--no-replace-objects", "-c", "core.fsmonitor=false", *args],
        cwd=REPO_DIR, check=True, capture_output=True, env=env,
    ).stdout


def _indexed_symlinks() -> dict[str, str]:
    try:
        index = _git_output("ls-files", "--stage", "--full-name", "-z")
    except (OSError, subprocess.CalledProcessError):
        return {}

    symlinks = {}
    for entry in index.split(b"\0")[:-1]:
        fields, path = entry.split(b"\t", 1)
        mode, blob, stage = fields.split()
        if mode == b"120000" and stage == b"0":
            symlinks[os.fsdecode(path)] = blob.decode("ascii")
    return symlinks


def _portable_relative_path(target: str) -> PurePosixPath:
    if (
        not target or target.startswith("/") or "\\" in target or ":" in target
        or any(ord(char) < 32 for char in target)
    ):
        raise ValueError("expected a portable relative path")
    return PurePosixPath(target)


def _read_compat_link(path: Path) -> str:
    target = os.readlink(path).replace(os.sep, "/")
    if os.name == "nt":
        # Windows returns absolute reparse targets with an extended path prefix.
        if target.startswith("//?/UNC/"):
            return "//" + target[8:]
        if target.startswith("//?/") and Path(target[4:]).is_absolute():
            return target[4:]
    return target


def _resolve_compat_path(parent: Path, path: PurePosixPath) -> Path:
    active_links: set[Path] = set()
    mount_point = getattr(stat, "IO_REPARSE_TAG_MOUNT_POINT", None)

    def resolve(current: Path, parts: tuple[str, ...]) -> Path:
        for part in parts:
            if not current.is_dir():
                raise ValueError("path traverses a non-directory")
            if part == "..":
                if current == REPO_DIR:
                    raise ValueError("path escapes the repository")
                current = current.parent
                continue

            candidate = current / part
            info = candidate.lstat()
            junction = mount_point is not None and getattr(info, "st_reparse_tag", None) == mount_point
            if not stat.S_ISLNK(info.st_mode) and not junction:
                current = candidate
                continue
            if candidate in active_links:
                raise ValueError("symlink loop")

            active_links.add(candidate)
            target = _read_compat_link(candidate)
            absolute = Path(target)
            if absolute.is_absolute():
                if not absolute.is_relative_to(REPO_DIR):
                    raise ValueError("path escapes the repository")
                raw = absolute.relative_to(REPO_DIR).as_posix()
                current = resolve(REPO_DIR, _portable_relative_path(raw).parts)
            else:
                current = resolve(current, _portable_relative_path(target).parts)
            if target.endswith(("/", "/.")) and not current.is_dir():
                raise ValueError("target does not exist as written")
            active_links.remove(candidate)
        return current

    return resolve(parent, path.parts)


def _compatibility_failures(moved: dict[str, str]) -> list[str]:
    indexed = _indexed_symlinks() if moved else {}
    failures = []
    for old, new in sorted(moved.items()):
        try:
            destination = _resolve_compat_path(REPO_DIR, _portable_relative_path(new))
        except FileNotFoundError:
            failures.append(f"moved target missing: {new}")
            continue
        except (OSError, RuntimeError, ValueError) as error:
            failures.append(f"invalid moved target: {new} ({error})")
            continue

        try:
            relative = _portable_relative_path(old)
            if not relative.name or relative.as_posix() != old or ".." in relative.parts:
                raise ValueError("expected a canonical repository path for the link")
            parent = _resolve_compat_path(REPO_DIR, relative.parent)
            link = parent / relative.name
            native = link.is_symlink()
            if native:
                target = _read_compat_link(link)
            elif old in indexed and link.is_file():
                placeholder = link.read_bytes()
                if placeholder != _git_output("cat-file", "blob", indexed[old]):
                    raise ValueError("placeholder differs from the indexed Git link target")
                target = placeholder.decode("utf-8")
            else:
                raise ValueError("expected a symlink or a tracked Git symlink placeholder")

            actual = _resolve_compat_path(parent, _portable_relative_path(target))
            if (native and not link.exists()) or (target.endswith(("/", "/.")) and not actual.is_dir()):
                raise ValueError("target does not exist as written")
            if actual != destination:
                raise ValueError(f"points to {actual.relative_to(REPO_DIR).as_posix()}")
        except (OSError, RuntimeError, ValueError, subprocess.CalledProcessError) as error:
            failures.append(f"invalid compat link: {old} -> {new} ({error})")
    return failures


def registry_checks(entries: list[dict[str, Any]], curation: dict[str, Any]) -> tuple[list[str], list[str]]:
    fails: list[str] = []
    warns: list[str] = []
    caps = curation.get("caps") or {}
    by_dir: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for e in entries:
        by_dir[e["dir"]].append(e)
    for name, group in sorted(by_dir.items()):
        if len(group) > 1:
            fails.append(f"duplicate skill name '{name}': " + ", ".join(e["path"] for e in group))
    names = set(by_dir)

    core_max = int(caps.get("core_per_domain_max", 12))
    for domain, members in (curation.get("core") or {}).items():
        cap = min(core_max, int(((curation.get("domains") or {}).get(domain) or {}).get("core_cap", core_max)))
        if len(members) > cap:
            fails.append(f"core set for '{domain}' has {len(members)} skills; cap is {cap}")
        for m in members:
            if m not in names:
                fails.append(f"core skill '{m}' ({domain}) not found")
            elif by_dir[m][0]["domain"] != domain:
                fails.append(f"core skill '{m}' is listed under '{domain}' but lives in '{by_dir[m][0]['domain']}'")

    agent_max = int(caps.get("agent_index_max", 12))
    fenced_agents = set((curation.get("fenced") or {}).keys())
    for agent, spec in (curation.get("agents") or {}).items():
        lst = spec.get("skills") or []
        if len(lst) > agent_max:
            fails.append(f"agent index '{agent}' lists {len(lst)} skills; cap is {agent_max}")
        if len(set(lst)) != len(lst):
            fails.append(f"agent index '{agent}' repeats a skill")
        for m in lst:
            if m not in names:
                fails.append(f"agent index '{agent}': skill '{m}' not found")
            elif not by_dir[m][0]["portable"] and agent not in fenced_agents:
                fails.append(f"agent index '{agent}' lists fenced skill '{m}'")
        if not (AGENTS_DIR / f"{agent}.md").is_file():
            fails.append(f"agents/{agent}.md missing")

    for rel in list((curation.get("review") or {}).keys()) + list((curation.get("deprecated") or {}).keys()):
        if not (REPO_DIR / rel / "SKILL.md").is_file():
            fails.append(f"curation path '{rel}' has no SKILL.md")
    for rel, spec in (curation.get("third_party") or {}).items():
        if not (REPO_DIR / rel / str(spec.get("license_file", "LICENSE"))).is_file():
            fails.append(f"third-party skill '{rel}' is missing its license file")
        if not re.fullmatch(r"[0-9a-f]{40}", str(spec.get("commit", ""))):
            fails.append(f"third-party skill '{rel}' needs a pinned 40-char commit")

    if GLOBAL_SET.is_file():
        globals_ = [ln.strip() for ln in GLOBAL_SET.read_text(encoding="utf-8").splitlines()
                    if ln.strip() and not ln.lstrip().startswith("#")]
        gmax = int(caps.get("global_install_max", 5))
        if len(globals_) > gmax:
            fails.append(f"global install set has {len(globals_)} skills; cap is {gmax}")

    fails.extend(_compatibility_failures(_load_json(MOVED_FILE).get("moved") or {}))

    soft = int(caps.get("library_soft_cap", 0) or 0)
    if soft and len(entries) > soft:
        warns.append(f"library has {len(entries)} skills; soft cap is {soft}. Retire before adding.")

    pool = [e for e in entries if e["status"] != "deprecated"]
    toks = {e["path"]: _tokens(_FULL_DESC.get(e["path"], e["summary"]) + " " + e["dir"].replace("-", " ")) for e in pool}
    pairs = []
    for i, a in enumerate(pool):
        for b in pool[i + 1:]:
            ta, tb = toks[a["path"]], toks[b["path"]]
            if len(ta) < 4 or len(tb) < 4:
                continue
            j = len(ta & tb) / len(ta | tb)
            if j >= 0.22:
                pairs.append((j, a["path"], b["path"]))
    for j, a, b in sorted(pairs, reverse=True)[:15]:
        warns.append(f"possible overlap ({j:.2f}): {a} <> {b}")
    return fails, warns


def registry_main(write: bool) -> int:
    entries, curation = build_registry()
    if not curation:
        print(f"ERROR: {CURATION_FILE} not found", file=sys.stderr)
        return 2
    outputs: dict[Path, str] = {REGISTRY_JSON: render_registry_json(entries, curation)}
    for agent in sorted((curation.get("agents") or {}).keys()):
        path = AGENTS_DIR / f"{agent}.md"
        current = path.read_text(encoding="utf-8") if path.is_file() else f"# {agent}\n"
        outputs[path] = _apply_agent_block(current, render_agent_block(agent, entries, curation))

    stale = []
    for p, output in outputs.items():
        if write:
            encoded = output.encode("utf-8")
            if p.is_file() and p.read_bytes() == encoded:
                continue
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_bytes(encoded)
            print(f"wrote {p.relative_to(REPO_DIR).as_posix()}")
        elif not p.is_file() or p.read_text(encoding="utf-8") != output:
            stale.append(p)
    fails, warns = registry_checks(entries, curation)
    for p in stale:
        fails.append(f"{p.relative_to(REPO_DIR).as_posix()} is stale: run scripts/generate-skill-registry.py --registry")
    portable = sum(e["portable"] for e in entries)
    print(f"registry: {len(entries)} skills ({portable} portable, {len(entries) - portable} fenced)")
    for w in warns:
        print(f"WARN  {w}")
    for f in fails:
        print(f"FAIL  {f}")
    print(f"registry check: {len(fails)} FAIL, {len(warns)} WARN")
    return 1 if fails else 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--registry", "--inject", dest="write", action="store_true",
                       help="regenerate the registry and agent tables (--inject is a legacy alias)")
    modes.add_argument("--check", "--dry-run", dest="check", action="store_true",
                       help="check the generated files and curation without writing (default)")
    return registry_main(write=parser.parse_args().write)


if __name__ == "__main__":
    sys.exit(main())
